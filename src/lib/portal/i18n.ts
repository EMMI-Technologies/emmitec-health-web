export type PortalKeyName = keyof typeof PT
const DICT: Record<PortalLang, Dict> = { pt: PT, en: EN }

/* ---------- idioma ---------- */

function hasSavedLocale(): boolean {
  try {
    return !!localStorage.getItem(LOCALE_STORAGE_KEY)
  } catch {
    return false
  }
}

function browserLang(): PortalLang {
  if (typeof navigator === 'undefined') return 'pt'
  const list = navigator.languages?.length ? navigator.languages : [navigator.language]
  return list.some((l) => /^pt\b/i.test(l ?? '')) ? 'pt' : 'en'
}

const explicit = ref(hasSavedLocale())

const lang = computed<PortalLang>(() => {
  if (!explicit.value) return browserLang()
  return i18n.global.locale.value === 'pt' ? 'pt' : 'en'
})

function setLang(l: PortalLang) {
  setLocale(l)
  explicit.value = true
}

/**
 * Texto no idioma do portal. Aceita chaves montadas (`mode.${m}`); chave que não existe aparece
 * crua na tela (o teste do portal confere que nenhuma aparece).
 */
function t(key: PortalKeyName | (string & {}), vars?: Record<string, string | number>): string {
  const k = key as PortalKeyName
  const s = DICT[lang.value][k] ?? PT[k] ?? key
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

export function usePortalLang() {
  return { lang, setLang, t }
}
